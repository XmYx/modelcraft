    /// The menu path (for the shortcuts editor's tree).
    pub fn menu(self) -> &'static str {
        use Action::*;
        match self {
            New | Open | Save | SaveAs | SaveIncremental | Import | ExportGlb | ExportObj | ExportStl | ExportFbx | Export3mf | ExportUsda => "File",
            Undo | Redo | Delete | Duplicate | Rename | SelectAll | SelectNone | TransformDialog | Preferences | Objects(_) => "Edit",
            Organize(_) => "Organize",
            AddPrimitive(_) | AddCage | AddDeformer(_) | AddField(_) | AddCloner(_) | AddCloneModifier(_) | AddArray(_) | AddSymmetry | AddGenerator(_)
            | AddGroup => "Create",
            Extrude | Inset | Bevel | LoopCut | Merge | Bridge | FillHole | Mirror(_) | Subdivide | Triangulate | Flip | Collapse | MeshTool(_) | Cut(_) => {
                "Mesh"
            }
            SelectLoop | SelectRing | GrowSelection | ShrinkSelection | Soft(_) => "Select",
            Brush(_) | Symmetry | MaskClear | MaskInvert | MaskFill | MaskOp(_) | BrushBigger | BrushSmaller | DetailUp | DetailDown | ShapeAdd
            | LiveDetail | EvenRemesh | Sculpt(_) => "Sculpt",
            ModeObject | ModeVertex | ModeEdge | ModeFace | ToolSelect | ToolMove | ToolRotate | ToolScale => "Tools",
            Palette | KeyboardShortcuts | About => "Help",
            ScriptWindow | ScriptRun | ScriptRunSelection | ScriptRecord | PluginsWindow => "Scripts",
            Anim(_) => "Animate",
            Rig(_) => "Rig",
            Sim(_) => "Simulate",
            Stage(a) => a.menu(),
            Render(_) => "Render",
            Bake(_) => "UV",
            Spline(_) => "Spline",
            Material(_) => "Render",
            Hair(_) => "Hair",
            Uv(_) => "UV",
            Paint(_) => "Paint",
            _ => "View",
        }
    }

